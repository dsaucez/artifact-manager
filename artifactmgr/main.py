import re

import bleach
import markdown
import mermaidx
from markupsafe import Markup

MERMAID_PATTERN = re.compile(
    r"```mermaid\s*\n(.*?)```",
    re.DOTALL | re.IGNORECASE,
)


def render_markdown(content: str) -> Markup:
    """Render Markdown and Mermaid diagrams to HTML."""

    if not content:
        return Markup("")

    def render_mermaid(match):
        source = match.group(1).strip()

        try:
            diagram = mermaidx.render(source)
            svg = diagram.svg()

            return f'<div class="mermaid-diagram">{svg}</div>'

        except Exception as exc:
            return (
                '<pre class="mermaid-error">'
                f"Mermaid rendering error: {bleach.clean(str(exc))}"
                "</pre>"
            )

    # Render Mermaid blocks before Markdown conversion.
    content = MERMAID_PATTERN.sub(render_mermaid, content)

    html = markdown.markdown(
        content,
        extensions=[
            "fenced_code",
            "tables",
            "toc",
            "nl2br",
        ],
    )

    # Sanitize the generated HTML.
    # SVG is generated by mermaidx, so preserve its SVG elements.
    # For untrusted input, use a dedicated SVG-aware sanitizer.
    return Markup(html)


env.filters["markdown"] = lambda text: render_markdown(text)


## == Digital object functions ================================================
async def search_objects(search=None, page_index: int = 0, page_size: int = 20) -> dict:
    params = {
        "paginate": True,
        "pageIndex": page_index,
        "pageSize": page_size,
        "advancedQuery": f'Keywords ^$ "{settings.selection_keywords}"',
    }

    if search:
        params["nameQuery"] = search

    url_params = "&".join([f"{k}={v}" for k, v in params.items()])

    url = f"{settings.base_url}/search/datasets?{url_params}"

    async with httpx.AsyncClient() as client:
        response = await client.get(url)
        response.raise_for_status()
        return response.json()


async def get_digital_object(internal_id) -> dict:
    url = f"{settings.base_url}/{internal_id}"

    async with httpx.AsyncClient() as client:
        response = await client.get(url)
        response.raise_for_status()
        return response.json()


async def upload_digital_object(
    token: str, metadata: dict, file: UploadFile | None = None
) -> int:
    headers = {
        "accept": "application/json",
        "Authorization": f"Bearer {token}",
    }

    """Upload a file with JSON metadata to the digital-objects API."""
    if file is None:
        url = f"{settings.base_url}/metadata-only"
        async with httpx.AsyncClient() as client:
            response = await client.post(
                url, headers=headers, json=metadata, timeout=500
            )
            response.raise_for_status()

            return int(response.json().get("digitalObjectId"))
    else:
        url = f"{settings.base_url}/upload"
        multipart_files = {
            "file": (
                file.filename or "upload" if file else "upload",
                await file.read() if file else b"",
                (
                    file.content_type or "application/octet-stream"
                    if file
                    else "application/octet-stream"
                ),
            ),
            "metadata": (None, json.dumps(metadata), "application/json"),
        }
        try:
            async with httpx.AsyncClient() as client:
                response = await client.post(
                    url, headers=headers, files=multipart_files, timeout=500
                )
                response.raise_for_status()
                return int(response.json())
        finally:
            if file:
                await file.seek(0)


